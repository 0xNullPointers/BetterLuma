    //  STEAMUI  BuildCompleteAppOverviewChange: re-assert removed_appids
    LM_HOOK(BuildCompleteAppOverviewChange, void*, void* pController,
            void* pChange, void* optionalCallbackSlot)
    {
        void* result = oBuildCompleteAppOverviewChange(pController, pChange, optionalCallbackSlot);

        // snapshot the removed set under lock, then mutate protobuf outside
        std::vector<AppId_t> snapshot;
        {
            std::lock_guard<std::mutex> lock(g_removalMutex);
            if (!g_removedAppIds.empty())
                snapshot.assign(g_removedAppIds.begin(), g_removedAppIds.end());
        }
        if (!snapshot.empty() && pChange && oRepeatedFieldUint32_Add) {
            auto* field = static_cast<::CAppOverview_Change*>(pChange)->mutable_removed_appid();
            for (AppId_t appId : snapshot)
                oRepeatedFieldUint32_Add(field, &appId);
            LOG_STEAMUICH_DEBUG("BuildCompleteAppOverviewChange: appended {} removed_appid entries", snapshot.size());
        }
        return result;
    }

    //  STEAMUI  SerializeAchievements: ensure global percentages loaded flag is set
    using FindAppStats_t = int(__fastcall*)(void* pMap, const AppId_t* pAppId);
    inline FindAppStats_t oFindAppStats = nullptr;
    inline size_t g_appStatsMapOffset   = 0x6a8;
    inline size_t g_appStatsArrayOffset = 0x6d8;

    static void TryMarkStatsLoaded(void* pController, AppId_t appId) {
        if (!pController || appId == 0 || !oFindAppStats) return;
        __try {
            void* pMap = static_cast<uint8_t*>(pController) + g_appStatsMapOffset;
            int index = oFindAppStats(pMap, &appId);
            if (index >= 0) {
                uint8_t* pArray = *reinterpret_cast<uint8_t**>(static_cast<uint8_t*>(pController) + g_appStatsArrayOffset);
                if (pArray) {
                    uint8_t* pStatsEntry = pArray + 8 + (static_cast<size_t>(index) * 0x50);
                    pStatsEntry[0x20] = 0; // bLoading = false
                    pStatsEntry[0x21] = 1; // bUserStatsLoaded = true
                    pStatsEntry[0x22] = 1; // bGlobalStatsLoaded = true
                }
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {
        }
    }

    static AppId_t SafeGetAppId(void* pApp) {
        if (!pApp) return 0;
        AppId_t appId = 0;
        __try {
            void** vfptr = *reinterpret_cast<void***>(pApp);
            if (vfptr && vfptr[0]) {
                auto pfnGetAppID = reinterpret_cast<AppId_t(__fastcall*)(void*)>(vfptr[0]);
                appId = pfnGetAppID(pApp);
            }
            if (appId == 0) {
                uint64_t gameId = *reinterpret_cast<const uint64_t*>(static_cast<const uint8_t*>(pApp) + 8);
                appId = static_cast<AppId_t>(gameId & 0xFFFFFF);
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            appId = 0;
        }
        return appId;
    }

    LM_HOOK(SerializeAchievements, void*, void* pController, void* pWriter, void* pApp)
    {
        if (pController && pApp)
        {
            AppId_t appId = SafeGetAppId(pApp);
            if (appId != 0)
            {
                uint64_t gameId = 0;
                __try {
                    gameId = *reinterpret_cast<const uint64_t*>(static_cast<const uint8_t*>(pApp) + 8);
                } __except (EXCEPTION_EXECUTE_HANDLER) {
                    gameId = appId;
                }
                GlobalAchievementManager::EnsureLoaded(appId, gameId);

                if (GlobalAchievementManager::HasData(appId))
                {
                    TryMarkStatsLoaded(pController, appId);
                }
            }
        }

        return oSerializeAchievements(pController, pWriter, pApp);
    }

    //  STEAMUI  CSteamUIAppControllerRunFrame: drain live library queues
    LM_HOOK(CSteamUIAppControllerRunFrame, void*, void* pController)
    {
        static auto lastPackageRetry = std::chrono::steady_clock::now() - 1s;
        static uint32_t runFrameRetryLogs = 0;
        auto now = std::chrono::steady_clock::now();
        if (now - lastPackageRetry >= 1s) {
            lastPackageRetry = now;
            SteamCapture::TryStartupPackageInjection("steamui-runframe-retry");
            ++runFrameRetryLogs;
            if (runFrameRetryLogs == 1 || runFrameRetryLogs % 30 == 0) {
                LOG_STEAMUICH_DEBUG("RunFrame: startup package retry tick={}", runFrameRetryLogs);
            }
        }

        if (oMarkAppChange && g_pAppChangeSource)
        {
            std::vector<AppId_t> drainingRemovals;
            std::vector<AppId_t> drainingTouches;
            {
                std::lock_guard<std::mutex> lock(g_removalMutex);
                drainingRemovals.swap(g_pendingRemovals);
                drainingTouches.swap(g_pendingTouches);
            }
            if (oGetAppByID)
            {
                for (AppId_t appId : drainingRemovals)
                {
                    if (LuaLoader::IsOwned(appId))
                    {
                        LOG_STEAMUICH_DEBUG("RunFrame: appId {} is owned again, skipping removal", appId);
                        continue;
                    }
                    if (CSteamApp* pApp = static_cast<CSteamApp*>(oGetAppByID(pController, appId, false)))
                    {
                        pApp->OwnershipFlags = k_EAppOwnershipFlags_None;
                        if (pApp->AppStateFlags == k_EAppStateUninstalled)
                        {
                            std::lock_guard<std::mutex> lock(g_removalMutex);
                            g_removedAppIds.insert(appId);
                        }
                    }
                    oMarkAppChange(g_pAppChangeSource, appId, 2); // AppInfoOrConfig
                }
            }
            else if (!drainingRemovals.empty())
            {
                std::lock_guard<std::mutex> lock(g_removalMutex);
                g_pendingRemovals.insert(g_pendingRemovals.end(),
                                         drainingRemovals.begin(),
                                         drainingRemovals.end());
            }
            for (AppId_t appId : drainingTouches)
            {
                {
                    std::lock_guard<std::mutex> lock(g_removalMutex);
                    g_removedAppIds.erase(appId);
                }
                oMarkAppChange(g_pAppChangeSource, appId, 2); // AppInfoOrConfig
                LOG_STEAMUICH_DEBUG("RunFrame: appId {} touched for live library refresh", appId);
            }
        }
        return oCSteamUIAppControllerRunFrame(pController);
    }

